#!/usr/bin/env python3
"""Build balapan-single.html: one self-contained file with all CSS and JS inlined.

Usage:  python3 build-single.py
Reads index.html, replaces everything between <!-- build:css --> … <!-- /build:css -->
and <!-- build:js --> … <!-- /build:js --> with inline <style>/<script> blocks.
Google Fonts stay as an external <link> (the page falls back to system fonts offline).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "index.html")
OUT = os.path.join(ROOT, "balapan-single.html")

def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()

def block(html, name):
    m = re.search(r"<!-- build:%s -->(.*?)<!-- /build:%s -->" % (name, name), html, re.S)
    if not m:
        sys.exit("missing build:%s markers in index.html" % name)
    return m

def inline_css(chunk):
    out = []
    for tag in re.findall(r"<link[^>]+>", chunk):
        href = re.search(r'href="([^"]+)"', tag).group(1)
        media = re.search(r'media="([^"]+)"', tag)
        css = read(href)
        attr = ' media="%s"' % media.group(1) if media else ""
        out.append("<style data-src=\"%s\"%s>\n%s\n</style>" % (href, attr, css))
    return "\n".join(out)

def inline_js(chunk):
    out = []
    for src in re.findall(r'<script src="([^"]+)"></script>', chunk):
        js = read(src).replace("</script", "<\\/script")
        out.append("<script data-src=\"%s\">\n%s\n</script>" % (src, js))
    return "\n".join(out)

def favicon(html):
    svg = read("assets/favicon.svg").strip()
    from urllib.parse import quote
    uri = "data:image/svg+xml," + quote(svg)
    return html.replace('href="assets/favicon.svg"', 'href="%s"' % uri)

def main():
    html = read("index.html")
    c = block(html, "css"); html = html[:c.start()] + inline_css(c.group(1)) + html[c.end():]
    j = block(html, "js"); html = html[:j.start()] + inline_js(j.group(1)) + html[j.end():]
    html = favicon(html)
    html = html.replace("<head>", "<head>\n  <!-- Generated by build-single.py from index.html. Do not edit by hand. -->", 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(html)
    print("wrote %s (%.0f KB)" % (os.path.relpath(OUT, ROOT), os.path.getsize(OUT) / 1024))

if __name__ == "__main__":
    main()
